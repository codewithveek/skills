import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { EasingSpec } from "../runtime/motion-preset";
import type { FittedBeat, PresetCluster } from "./types";

export interface PresetOutputs {
  readonly outDir: string;
  readonly sourceName: string;
  readonly fittedBeats: readonly FittedBeat[];
  readonly acceptedBeatIds: ReadonlySet<number>;
  readonly clusters: readonly PresetCluster[];
  /** Name of the generated constant, e.g. SAAS_LAUNCH. */
  readonly exportName: string;
  /** Import path of the MotionPreset type from the generated module. */
  readonly runtimeImport: string;
}

function formatEasing(easing: EasingSpec): string {
  return easing.kind === "spring"
    ? `spring d=${easing.damping} k=${easing.stiffness} m=${easing.mass}${easing.overshootClamping ? " clamped" : ""}`
    : `bezier(${easing.x1}, ${easing.y1}, ${easing.x2}, ${easing.y2})`;
}

function pascalCase(constantName: string): string {
  return constantName.toLowerCase().split("_").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
}

function presetModuleSource(outputs: PresetOutputs): string {
  const entries = outputs.clusters.map((cluster) => {
    const preset = {
      id: cluster.id,
      channel: cluster.channel,
      durationMs: cluster.medianDurationMs,
      travel: cluster.channel === "progress" ? 1 : cluster.medianTravel,
      easing: cluster.easing,
    };
    const comment = `/** ${cluster.memberBeatIds.length} beats from ${outputs.sourceName}; mean fit RMSE ${cluster.meanProgressRmse}. Beats: ${cluster.memberBeatIds.join(", ")} */`;
    return `  ${comment}\n  ${JSON.stringify(cluster.id)}: ${JSON.stringify(preset)},`;
  });
  return [
    "// Generated by motion-lab `npm run fit-presets`. Do not edit by hand; re-run the fitter instead.",
    `import type { MotionPreset } from "${outputs.runtimeImport}";`,
    "",
    `export const ${outputs.exportName} = {`,
    ...entries,
    "} as const satisfies Record<string, MotionPreset>;",
    "",
    `export type ${pascalCase(outputs.exportName)}PresetId = keyof typeof ${outputs.exportName};`,
    "",
  ].join("\n");
}

function reportMarkdown(outputs: PresetOutputs): string {
  const accepted = outputs.fittedBeats.filter((beat) => outputs.acceptedBeatIds.has(beat.beatId));
  const springCount = accepted.filter((beat) => beat.best.easing.kind === "spring").length;
  const lines = [
    `# Preset fit report — ${outputs.sourceName}`,
    "",
    `- Beats fitted: ${outputs.fittedBeats.length}; accepted into the library: ${accepted.length} (${springCount} spring, ${accepted.length - springCount} bezier)`,
    `- Library presets (shape clusters): ${outputs.clusters.length}`,
    "",
    "## Library",
    "",
    "| Preset | Channel | Easing | Median duration | Median travel | Beats | Mean RMSE |",
    "|---|---|---|---|---|---|---|",
    ...outputs.clusters.map((c) =>
      `| ${c.id} | ${c.channel} | ${formatEasing(c.easing)} | ${c.medianDurationMs} ms | ${c.medianTravel} | ${c.memberBeatIds.length} | ${c.meanProgressRmse} |`),
    "",
    "## Every beat",
    "",
    "| Beat | Frames | Scene | Channel | Travel | Best easing | RMSE | Nearest named | Quality | In library |",
    "|---|---|---|---|---|---|---|---|---|---|",
    ...outputs.fittedBeats.map((b) =>
      `| ${b.beatId} | ${b.startFrame}–${b.endFrame} | ${b.scene} | ${b.channel} | ${b.travel} ${b.unit} | ${formatEasing(b.best.easing)} | ${b.best.progressRmse.toFixed(4)} | ${b.nearestNamedEasing.name} (${b.nearestNamedEasing.progressRmse.toFixed(3)}) | ${b.signalQuality} | ${outputs.acceptedBeatIds.has(b.beatId) ? "yes" : "no"} |`),
    "",
  ];
  return lines.join("\n");
}

export async function writePresetOutputs(outputs: PresetOutputs): Promise<string[]> {
  await mkdir(outputs.outDir, { recursive: true });
  const files: Array<[string, string]> = [
    ["fitted-beats.json", JSON.stringify(outputs.fittedBeats, null, 1)],
    ["preset-library.json", JSON.stringify(outputs.clusters, null, 1)],
    ["motion-presets.ts", presetModuleSource(outputs)],
    ["fit-report.md", reportMarkdown(outputs)],
  ];
  await Promise.all(files.map(([name, content]) => writeFile(join(outputs.outDir, name), content)));
  return files.map(([name]) => join(outputs.outDir, name));
}
